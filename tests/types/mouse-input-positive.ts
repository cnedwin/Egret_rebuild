import {createMouseInput} from '@egret/engine/web/input';
import type {MouseInputOptions,MouseInput,MouseInputState,MouseInputEvents,MouseInputPayload,MouseInputCancelReason} from '@egret/engine/web/input';
import type {Engine,Scope,EventType} from '@egret/engine';
type Equal<A,B>=(<T>()=>T extends A?1:2) extends (<T>()=>T extends B?1:2)?true:false;
type Expect<T extends true>=T;
type Options=Expect<Equal<MouseInputOptions,{readonly engine:Engine;readonly scope:Scope;readonly width:number;readonly height:number;readonly maxNodes?:number}>>;
type State=Expect<Equal<MouseInputState,'idle'|'pressed'|'closed'>>;
type Reason=Expect<Equal<MouseInputCancelReason,'pointercancel'|'blur'|'pagehide'>>;
type Payload=Expect<Equal<MouseInputPayload,{readonly pointerId:number;readonly globalX:number;readonly globalY:number;readonly pointerType:'mouse';readonly button:0}>>;
type Events=Expect<Equal<MouseInputEvents,{readonly begin:EventType<MouseInputPayload>;readonly end:EventType<MouseInputPayload>;readonly activate:EventType<MouseInputPayload>;readonly cancel:EventType<MouseInputPayload&{readonly reason:MouseInputCancelReason}>}>>;
type PublicKeys=Expect<Equal<Extract<keyof MouseInput,string>,'state'|'events'|'dispose'>>;
type Factory=Expect<Equal<typeof createMouseInput,(options:MouseInputOptions)=>MouseInput>>;
declare const engine:Engine;
declare const scope:Scope;
const input:MouseInput=createMouseInput({engine,scope,width:100,height:80,maxNodes:4096});
const state:MouseInputState=input.state;
const begin:EventType<MouseInputPayload>=input.events.begin;
const cancel:EventType<MouseInputPayload&{readonly reason:MouseInputCancelReason}>=input.events.cancel;
const retired:void=input.dispose();
void state;void begin;void cancel;void retired;
export type ExactMouseInputContract=Options|State|Reason|Payload|Events|PublicKeys|Factory;
