import { createHash, randomUUID } from 'node:crypto';
import fs from 'node:fs';
import http from 'node:http';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';
import { PNG } from 'pngjs';
import {
  createProjectStore,
  openProjectHistory,
  parseProjectSnapshot,
  parseProjectTransaction,
  serializeProjectSnapshot
} from '@egret/project';
import { fingerprintFile, logicalPath } from './lib/file-identity.mjs';
import { browserBuildTypes, verifyGame } from './verify-game.mjs';

const checkpoints = ['first-action', 'restart', 'first-action-after-restart'];
const entry = 'index.html';
const projectFile = 'project.json';
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const json = value => JSON.stringify(value, null, 2) + '\n';

function refuse(code, message, details) {
  throw Object.assign(new Error(message), { code, details });
}

function take(result) {
  if (!result.ok) refuse('PLAYTEST_PROJECT_REFUSED', 'The project SDK rejected the input.', result.diagnostics);
  return result.value;
}

function artifactFile(owner, key) {
  logicalPath(key);
  if (key.split('/').some(piece => piece.startsWith('.')) || !Object.hasOwn(browserBuildTypes, path.extname(key))) {
    refuse('PLAYTEST_ARTIFACT_PATH', 'An explicit browser build file is required: ' + key);
  }
  const identity = fingerprintFile(owner, key);
  const bytes = fs.readFileSync(path.join(owner, key));
  if (digest(bytes) !== identity.sha256) refuse('PLAYTEST_ARTIFACT_CHANGED', 'File changed while being staged: ' + key);
  return bytes;
}

function manifestOf(files) {
  const manifest = [...files.keys()].sort().map(key => {
    const bytes = files.get(key);
    return { path: key, bytes: bytes.length, sha256: digest(bytes) };
  });
  return { files: manifest, sha256: digest(JSON.stringify(manifest)) };
}

function openRun(folder) {
  const report = JSON.parse(fs.readFileSync(path.join(folder, 'report.json'), 'utf8'));
  const files = new Map(
    report.artifact.files.map(({ path: key }) => [key, artifactFile(path.join(folder, 'web'), key)])
  );
  // Read each admitted file into memory before serving; later disk edits cannot change a preview.
  if (
    report.schemaVersion !== 1 ||
    !files.has(entry) ||
    !files.has(projectFile) ||
    JSON.stringify(manifestOf(files)) !== JSON.stringify(report.artifact)
  ) {
    refuse('PLAYTEST_ARTIFACT_CHANGED', 'The build no longer matches its desktop report.');
  }
  return { files, report };
}

function startProject(options, scenarioSha256) {
  if (options.after) {
    const previous = openRun(options.after);
    if (previous.report.status !== 'failed' || previous.report.scenarioSha256 !== scenarioSha256) {
      refuse('PLAYTEST_REPAIR_BASE', 'Repair requires a failed run and the same scenario bytes.');
    }
    const store = take(openProjectHistory(fs.readFileSync(path.join(options.after, 'history.json'), 'utf8')));
    const before = take(serializeProjectSnapshot(store.getSnapshot()));
    if (!Buffer.from(before).equals(previous.files.get(projectFile))) {
      refuse('PLAYTEST_REPAIR_BASE', 'Project history does not match the failed build.');
    }
    const transaction = take(parseProjectTransaction(fs.readFileSync(options.transaction, 'utf8')));
    // Keep revision and ownership checks in ProjectStore, including scope and stale revision refusal.
    const result = store.commit(transaction);
    if (result.status !== 'committed') {
      refuse('PLAYTEST_TRANSACTION_REFUSED', 'The repair did not commit to the failed revision.', result.diagnostics);
    }
    const { addedFileIds, changedFileIds, removedFileIds } = result.receipt.diff;
    if (addedFileIds.length || changedFileIds.length || removedFileIds.length) {
      refuse('PLAYTEST_REBUILD_REQUIRED', 'File edits require rebuilding the game and starting a new run.');
    }
    return {
      store,
      files: previous.files,
      repair: { previousArtifactSha256: previous.report.artifact.sha256, receipt: result.receipt }
    };
  }
  const snapshot = take(parseProjectSnapshot(fs.readFileSync(options.project, 'utf8')));
  const keys = [entry, ...(options.file ?? [])];
  const portableKeys = new Set(keys.map(key => key.toLowerCase()));
  if (portableKeys.size !== keys.length || portableKeys.has(projectFile)) {
    refuse(
      'PLAYTEST_ARTIFACT_PATH',
      'Build paths must be unique across platforms. project.json is generated by the tool.'
    );
  }
  return {
    store: take(createProjectStore(snapshot)),
    files: new Map(keys.map(key => [key, artifactFile(options.web, key)])),
    repair: null
  };
}

export async function runPlaytest(options) {
  const scenario = fs.readFileSync(options.scenario);
  const scenarioSha256 = digest(scenario);
  const { store, files, repair } = startProject(options, scenarioSha256);
  const snapshot = store.getSnapshot();
  files.set(projectFile, Buffer.from(take(serializeProjectSnapshot(snapshot))));
  const artifact = manifestOf(files);
  const out = options.out;
  fs.mkdirSync(out);
  for (const [key, bytes] of files) {
    const destination = path.join(out, 'web', key);
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.writeFileSync(destination, bytes, { flag: 'wx' });
  }
  fs.writeFileSync(path.join(out, 'history.json'), take(store.exportHistory()));
  const stagedScenario = path.join(out, 'scenario.mjs');
  fs.writeFileSync(stagedScenario, scenario, { flag: 'wx' });
  const report = {
    schemaVersion: 1,
    projectId: snapshot.projectId,
    revision: snapshot.revision,
    scenarioSha256,
    artifact,
    repair,
    status: 'failed',
    verification: null,
    diagnostic: null
  };
  try {
    const { chromium } = await import(pathToFileURL(options.playwright).href);
    const driver = options.executable
      ? { launch: settings => chromium.launch({ ...settings, executablePath: options.executable }) }
      : chromium;
    report.verification = await verifyGame({
      chromium: driver,
      PNG,
      file: path.join(out, 'web', entry),
      out: path.join(out, 'browser'),
      script: await import(pathToFileURL(stagedScenario).href),
      scriptOnly: true,
      filePaths: [...files.keys()]
    });
    const played = report.verification.checks.played;
    if (!report.verification.pass) {
      report.diagnostic = played?.diagnostic ?? {
        code: 'PLAYTEST_BROWSER_FAILED',
        message: 'Inspect the failed browser checks.'
      };
    } else if (checkpoints.every((name, index) => played.checkpoints[index] === name)) {
      report.status = 'passed';
    } else {
      report.diagnostic = {
        code: 'PLAYTEST_STEPS_MISSING',
        message: 'Confirm the required checkpoints in order.',
        details: checkpoints
      };
    }
    if (
      manifestOf(new Map([...files.keys()].map(key => [key, artifactFile(path.join(out, 'web'), key)]))).sha256 !==
      artifact.sha256
    )
      refuse('PLAYTEST_ARTIFACT_CHANGED', 'Build files changed during verification.');
  } catch (error) {
    report.status = 'failed';
    report.diagnostic = { code: error.code ?? 'PLAYTEST_START_FAILED', message: error.message };
  }
  fs.writeFileSync(path.join(out, 'report.json'), json(report));
  return report;
}

function writeQr(qrcode, url, out) {
  const qr = qrcode(0, 'M');
  qr.addData(url);
  qr.make();
  const count = qr.getModuleCount();
  const scale = 8;
  const margin = 4;
  const width = (count + 2 * margin) * scale;
  const png = new PNG({ width, height: width });
  png.data.fill(255);
  for (let y = 0; y < count * scale; y++) {
    for (let x = 0; x < count * scale; x++) {
      if (!qr.isDark(Math.floor(y / scale), Math.floor(x / scale))) continue;
      const index = ((y + margin * scale) * width + x + margin * scale) * 4;
      png.data.fill(0, index, index + 3);
    }
  }
  fs.writeFileSync(out, PNG.sync.write(png));
}

export async function startPreview(folder, address, qrcode) {
  const { files, report } = openRun(folder);
  if (report.status !== 'passed') refuse('PLAYTEST_PREVIEW_FAILED', 'Preview requires a passing desktop report.');
  const octets = address.split('.').map(Number);
  if (
    octets.length !== 4 ||
    octets.join('.') !== address ||
    !octets.every(x => Number.isInteger(x) && x >= 0 && x < 256) ||
    !(
      address === '127.0.0.1' ||
      octets[0] === 10 ||
      (octets[0] === 192 && octets[1] === 168) ||
      (octets[0] === 172 && octets[1] >= 16 && octets[1] <= 31)
    )
  ) {
    refuse('PLAYTEST_PREVIEW_ADDRESS', 'Choose one private IPv4 LAN address or 127.0.0.1.');
  }
  const prefix = '/' + randomUUID() + '/';
  // The LAN URL resolves only to the verified in-memory manifest, never to disk paths or reports.
  const routes = new Map(
    [...files].map(([key, bytes]) => [
      '/' + key.split('/').map(encodeURIComponent).join('/'),
      { bytes, type: browserBuildTypes[path.extname(key)] }
    ])
  );
  const server = http.createServer((request, response) => {
    const pathname = request.url?.split('?', 1)[0] ?? '';
    const key = pathname.startsWith(prefix) ? pathname.slice(prefix.length - 1) : pathname;
    const route = routes.get(key);
    if (!route || (request.method !== 'GET' && request.method !== 'HEAD')) {
      response.writeHead(404).end();
      return;
    }
    response
      .writeHead(200, {
        'Content-Type': route.type,
        'Content-Length': route.bytes.length,
        'Cache-Control': 'no-store',
        'X-Egret-Artifact-Sha256': report.artifact.sha256,
        'X-Content-Type-Options': 'nosniff'
      })
      .end(request.method === 'HEAD' ? undefined : route.bytes);
  });
  await new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(0, address, resolve);
  });
  try {
    const url = 'http://' + address + ':' + server.address().port + prefix + entry;
    const qr = path.join(folder, 'preview-qr.png');
    writeQr(qrcode, url, qr);
    return { server, url, qr, artifactSha256: report.artifact.sha256 };
  } catch (error) {
    server.close();
    throw error;
  }
}

const usage = [
  'Usage:',
  '  node tools/agent-playtest.mjs run --project <snapshot> --web <build folder> --file <relative file> ...',
  '      --scenario <self-contained mjs> --playwright <index.mjs> --out <new folder> [--executable <Chromium>]',
  '  node tools/agent-playtest.mjs run --after <failed run> --transaction <json>',
  '      --scenario <same mjs> --playwright <index.mjs> --out <new folder> [--executable <Chromium>]',
  '  node tools/agent-playtest.mjs preview --run <passing run> --address <private IPv4> --qr-module <qrcode.mjs>'
].join('\n');

async function main([command, ...args]) {
  const strings = names => Object.fromEntries(names.map(name => [name, { type: 'string' }]));
  if (command === 'run') {
    const { values } = parseArgs({
      args,
      options: {
        ...strings(['project', 'web', 'scenario', 'playwright', 'out', 'executable', 'after', 'transaction']),
        file: { type: 'string', multiple: true }
      }
    });
    if (
      !values.scenario ||
      !values.playwright ||
      !values.out ||
      (values.after
        ? !values.transaction || values.project || values.web || values.file
        : !values.project || !values.web || values.transaction)
    )
      refuse('PLAYTEST_ARGUMENTS', usage);
    for (const key of Object.keys(values)) if (key !== 'file') values[key] = path.resolve(values[key]);
    const report = await runPlaytest(values);
    console.log(json(report));
    if (report.status !== 'passed') process.exitCode = 1;
  } else if (command === 'preview') {
    const { values } = parseArgs({ args, options: strings(['run', 'address', 'qr-module']) });
    if (!values.run || !values.address || !values['qr-module']) refuse('PLAYTEST_ARGUMENTS', usage);
    const { default: qrcode } = await import(pathToFileURL(path.resolve(values['qr-module'])).href);
    if (typeof qrcode !== 'function') refuse('PLAYTEST_QR_MODULE', 'Choose a qrcode-generator module.');
    const { server, ...preview } = await startPreview(path.resolve(values.run), values.address, qrcode);
    const close = () => {
      server.close();
      server.closeAllConnections();
    };
    server.requestTimeout = 15000;
    server.maxConnections = 8;
    const timeout = setTimeout(close, 15 * 60 * 1000);
    process.once('SIGINT', close);
    process.once('SIGTERM', close);
    server.once('close', () => {
      clearTimeout(timeout);
      process.removeListener('SIGINT', close);
      process.removeListener('SIGTERM', close);
    });
    console.log(json(preview));
  } else {
    refuse('PLAYTEST_ARGUMENTS', usage);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch(error => {
    console.error(
      json({
        status: 'failed',
        diagnostic: { code: error.code ?? 'PLAYTEST_FAILED', message: error.message, details: error.details }
      })
    );
    process.exitCode = 1;
  });
}
